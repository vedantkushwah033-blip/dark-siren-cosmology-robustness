import importlib.util
from pathlib import Path

import numpy as np
import pytest

MODULE_PATH = Path(__file__).resolve().parents[1] / "scripts" / "run_fixed_truth_coverage_audit.py"
SPEC = importlib.util.spec_from_file_location("fixed_truth_coverage_audit", MODULE_PATH)
module = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(module)


def test_normalized_cdf_is_monotone_and_ends_at_one():
    grid = np.linspace(50.0, 90.0, 401)
    posterior = np.exp(-0.5 * ((grid - 70.0) / 5.0) ** 2)
    cdf = module.normalized_cdf(grid, posterior)
    assert cdf[0] == pytest.approx(0.0)
    assert cdf[-1] == pytest.approx(1.0)
    assert np.all(np.diff(cdf) >= 0.0)


def test_central_interval_contains_median_and_is_ordered():
    grid = np.linspace(50.0, 90.0, 1601)
    posterior = np.exp(-0.5 * ((grid - 70.0) / 4.0) ** 2)
    cdf = module.normalized_cdf(grid, posterior)
    lo68, hi68 = module.central_interval(grid, cdf, 0.68)
    lo95, hi95 = module.central_interval(grid, cdf, 0.95)
    median = float(np.interp(0.5, cdf, grid))
    assert lo95 <= lo68 < median < hi68 <= hi95


def test_invalid_posterior_is_rejected():
    grid = np.array([0.0, 1.0, 2.0])
    with pytest.raises(ValueError):
        module.normalized_cdf(grid, np.array([1.0, -0.1, 1.0]))
    with pytest.raises(ValueError):
        module.normalized_cdf(grid, np.array([0.0, 0.0, 0.0]))


def test_interval_level_has_expected_width_order():
    grid = np.linspace(50.0, 90.0, 1601)
    posterior = np.exp(-0.5 * ((grid - 70.0) / 3.0) ** 2)
    cdf = module.normalized_cdf(grid, posterior)
    lo68, hi68 = module.central_interval(grid, cdf, 0.68)
    lo95, hi95 = module.central_interval(grid, cdf, 0.95)
    assert hi95 - lo95 > hi68 - lo68


def test_gaussian_benchmark_matches_analytic_central_intervals():
    """Numerical CDF quantiles should reproduce a known Gaussian posterior."""
    mean, sigma = 70.0, 4.0
    grid = np.linspace(30.0, 120.0, 18001)
    posterior = np.exp(-0.5 * ((grid - mean) / sigma) ** 2)
    cdf = module.normalized_cdf(grid, posterior)

    median = float(np.interp(0.5, cdf, grid))
    lo68, hi68 = module.central_interval(grid, cdf, 0.68)
    lo95, hi95 = module.central_interval(grid, cdf, 0.95)

    assert median == pytest.approx(mean, abs=0.02)
    # Central 68% and 95% Gaussian intervals are approximately ±0.994σ and ±1.960σ.
    assert lo68 == pytest.approx(mean - 0.9944579 * sigma, abs=0.04)
    assert hi68 == pytest.approx(mean + 0.9944579 * sigma, abs=0.04)
    assert lo95 == pytest.approx(mean - 1.959964 * sigma, abs=0.04)
    assert hi95 == pytest.approx(mean + 1.959964 * sigma, abs=0.04)


def test_single_host_likelihood_peaks_near_injected_h0():
    """A noiseless distance generated by cz/H0 should peak near injected H0."""
    c_km_s = 299792.458
    h0_true = 72.0
    z = 0.035
    distance = c_km_s * z / h0_true
    sigma = 0.01 * distance
    grid = np.linspace(30.0, 120.0, 18001)
    likelihood = np.exp(-0.5 * ((distance - c_km_s * z / grid) / sigma) ** 2)
    cdf = module.normalized_cdf(grid, likelihood)
    median = float(np.interp(0.5, cdf, grid))
    assert median == pytest.approx(h0_true, abs=0.2)
